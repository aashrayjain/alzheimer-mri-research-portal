"""Export and reporting helpers for JSON, CSV, and summary cards."""
from __future__ import annotations

import json
from datetime import datetime
from typing import Dict, Any, List
import pandas as pd


def generate_prediction_export_payload(
    model_name: str,
    predictions: Dict[str, Any],
    metadata: Dict[str, Any],
    device_info: str
) -> Dict[str, Any]:
    """Builds a structured dictionary summarizing an MRI prediction session."""
    return {
        "timestamp": datetime.now().isoformat(),
        "model_selected": model_name,
        "device_used": device_info,
        "prediction_summary": {
            "predicted_class": predictions.get("predicted_class"),
            "confidence": predictions.get("confidence"),
            "confidence_percentage": predictions.get("confidence_percentage"),
            "latency_ms": predictions.get("latency_ms"),
        },
        "all_class_probabilities": predictions.get("class_probabilities"),
        "model_metadata": {
            "checkpoint_file": metadata.get("checkpoint_file"),
            "best_validation_loss": metadata.get("best_validation_loss"),
            "best_epoch_in_history": metadata.get("best_epoch_in_history"),
            "total_parameters": metadata.get("total_parameters"),
        },
        "clinical_disclaimer": (
            "This export was generated by an educational and research prototype. "
            "These findings do not constitute clinical advice or medical diagnosis."
        ),
    }


def export_payload_to_json(payload: Dict[str, Any]) -> str:
    """Serializes prediction export to formatted JSON string."""
    return json.dumps(payload, indent=2)

